  static String translate(String text, String lang) {
    if (lang == 'Indonesia') return text;
    
    final targetLang = (lang == 'Inggris' || lang == 'English') ? 'en' : 'ar';
    
    // 1. Try general mapping
    if (_localizedMap.containsKey(text)) {
      return _localizedMap[text]?[targetLang] ?? text;
    }
    
    // 2. Try normalized general mapping (trimming, case issues)
    final trimmed = text.trim();
    if (_localizedMap.containsKey(trimmed)) {
      return _localizedMap[trimmed]?[targetLang] ?? text;
    }

    return text;
  }

  static String translateContent(String itemId, String fieldType, String originalText, String lang) {
    if (lang == 'Indonesia') return originalText;

    final targetLang = (lang == 'Inggris' || lang == 'English') ? 'en' : 'ar';
    
    // Check if we have specific content translations for this itemId (e.g. Doa title or Wirid item ID)
    if (_contentMap.containsKey(itemId) && _contentMap[itemId]!.containsKey(fieldType)) {
      return _contentMap[itemId]![fieldType]?[targetLang] ?? originalText;
    }

    // Fallback to general lookup
    return translate(originalText, lang);
  }
